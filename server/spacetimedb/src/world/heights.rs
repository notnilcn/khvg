//! Deterministic, crack-free ridge-based height field (PLAN.md §4.6 part A).
//!
//! Portions derived from Sota (v0.12, MIT © 2024 Roman Ardazishvili) — the ridge/height
//! pipeline (`ridge_impl/ridge_set_maker.cpp::construct`, `ridge_set.cpp::create_dfs_random`,
//! `core/general_utility.cpp::calculate_ridge_based_heights`, `ridge_impl/mountain_mesh.cpp`).
//! See THIRD_PARTY_NOTICES.md. What was canonicalized/simplified versus that reference:
//!
//! - Sota's ridge walk uses a hard-coded `std::mt19937(0)` and an unstable sort whose
//!   tie-break is implementation-defined, so it is not cross-run reproducible. Here the walk
//!   draws from the shared SplitMix64 PRNG (`prng.rs`) through an explicit, local draw counter
//!   threaded from the world seed (it never touches the generation pipeline's shared `draw`),
//!   and all group/member iteration is canonically sorted — no HashMap iteration order ever
//!   feeds the RNG or a write.
//! - Sota computes border/ridge distances per tile (corner wavefront maps and only the ridges
//!   whose endpoint lies near the tile), which leaves per-group seams and depends on neighbor
//!   visitation. Here every sample point is evaluated against GLOBAL border-edge and
//!   ridge-segment lists, so the field is a pure function of `(x, z, seed)` — the same world
//!   XZ always yields the same height, including the corner points shared by 3 hexes.
//! - Sota's stale min/max state (never reset between regenerations, `numeric_limits<float>::
//!   min()` positive-only init) and its iterative half-hex tessellation are not ported; this
//!   module only produces heights, and every bound is an explicit constant.
//!
//! Field shape, per sample point `p = (x, z)`:
//!
//! 1. `base(p)` — 2-octave `value_noise2d`, amplitude constant.
//! 2. Terrain classes (plain/hill/mountain, from `TERRAIN_CLASS_NOISE_SCALE`) bucket hexes
//!    into DSU groups. Classes only decide where ridge polylines are placed and which hex
//!    edges are class borders — they never switch the per-point formula, which is what keeps
//!    class borders seam-free.
//! 3. Mountain-class groups get a ridge polyline: a canonical-order walk over the group's hex
//!    centers (start = lexicographically smallest member, target = largest) that picks among
//!    unvisited same-group neighbors with the PRNG, then subdivides each connection with a
//!    small deterministic lateral jitter.
//! 4. `border_dist(p)` = min exact point-to-segment distance over every class-border edge
//!    (min with `BORDER_REACH_HEXES × hex_outer_radius`).
//!    `ridge_dist(p)` = the same over every ridge segment within `RIDGE_REACH_HEXES ×
//!    hex_outer_radius`; beyond that reach the ridge term is disabled (no distant phantom
//!    lift), with the reach falloff folded into an effective distance so the field stays
//!    continuous at the reach boundary.
//! 5. `t = border_dist / (border_dist + ridge_dist_eff)`, `y = lerp(base, RIDGE_TOP_HEIGHT, t)`,
//!    then Sota-style erosion and a global hill bump, clamped to
//!    `[0, ELEVATION_LEVELS × WORLD_HEIGHT_PER_LEVEL]`.
//!
//! Lockstep: the hex-corner convention mirrored here is the MST fork's
//! `MSTHexMath.hex_corner_offset(dir, size)` (client/addons/MarchingSquaresTerrain/algorithm/
//! terrain/mst_hex_math.gd:105-108) with `size` = hex outer radius — corner `dir` sits at
//! angle `60×dir − 30°` from the hex center generated by `hex_to_world` — and
//! `WORLD_HEIGHT_PER_LEVEL` mirrors `ElevationMapComponent.WorldHeightPerLevel`
//! (client/Scripts/Components/Terrain/ElevationMapComponent.cs). Both copies must change
//! together.
//!
//! Self-contained by design: takes plain `(q, r)` cells + a small config and returns a
//! `HashMap<(q, r), Vec<i16>>`, so it can be unit-tested outside SpacetimeDB.

