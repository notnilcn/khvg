use crate::main::global::{ELEVATION_LEVELS, TERRAIN_CLASS_NOISE_SCALE, WORLD_HEIGHT_PER_LEVEL};

use super::hex::{hex_to_world, HEX_NEIGHBOR_DELTAS};
use super::noise::{
    value_noise2d, HEIGHT_HILL_NOISE_SEED_OFFSET, HEIGHT_NOISE_OCTAVE2_SEED_OFFSET,
    HEIGHT_NOISE_SEED_OFFSET, RIDGE_NOISE_SEED_OFFSET, TERRAIN_CLASS_NOISE_SEED_OFFSET,
};
