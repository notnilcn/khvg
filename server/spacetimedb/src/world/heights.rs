/// Heights stored per hex: `[center, corner c0..c5]`, corners in `HEX_NEIGHBOR_DELTAS` order.
pub const HEIGHTS_PER_HEX: usize = 7;

// ===== Base terrain (2-octave value noise, constant amplitude) =====

const HEIGHT_BASE_OCTAVE1_SCALE: f32 = 0.0022;
const HEIGHT_BASE_OCTAVE1_WEIGHT: f32 = 0.65;
const HEIGHT_BASE_OCTAVE2_SCALE: f32 = 0.0065;
const HEIGHT_BASE_OCTAVE2_WEIGHT: f32 = 0.35;
/// Base height amplitude in world units (`base` spans `[0, HEIGHT_BASE_AMPLITUDE)`).
pub const HEIGHT_BASE_AMPLITUDE: f32 = WORLD_HEIGHT_PER_LEVEL * 2.5;

// ===== Terrain classes (DSU bucketing for ridge placement only) =====

/// Below this class-noise value a hex is PLAIN, below `TERRAIN_CLASS_MOUNTAIN_MAX` it is HILL
/// (bump-only terrain), above it MOUNTAIN (gets a ridge polyline).
const TERRAIN_CLASS_HILL_MAX: f32 = 0.58;
const TERRAIN_CLASS_MOUNTAIN_MAX: f32 = 0.75;

// ===== Ridge polylines =====

/// Mountain-top height in world units — above level 7 (`7 × WORLD_HEIGHT_PER_LEVEL`) so
/// erosion still leaves ridge vertices at level 7.
pub const RIDGE_TOP_HEIGHT: f32 = WORLD_HEIGHT_PER_LEVEL * 7.5;
/// How far (in hex outer radii) a ridge segment lifts terrain; beyond this the ridge term is
/// disabled, so distant ridges cause no phantom lift.
const RIDGE_REACH_HEXES: f32 = 8.0;
/// Segments per connection between two polyline hex centers.
const RIDGE_SUBDIVISIONS: usize = 4;
/// Max lateral jitter of an interior polyline vertex, in hex outer radii.
const RIDGE_LATERAL_JITTER_FRACTION: f32 = 0.2;

/// `border_dist` is capped here (in hex outer radii): deeper inside a class region the exact
/// distance stops mattering, because the blend `border/(border + ridge)` is already close to
/// its limit.
pub const BORDER_REACH_HEXES: f32 = 3.0;

// ===== Erosion & hill bump =====

const EROSION_NOISE_SCALE: f32 = 0.01;
/// Max height the Sota-style erosion term subtracts from the ridge-top blend.
pub const EROSION_AMPLITUDE: f32 = WORLD_HEIGHT_PER_LEVEL * 0.5;
const HEIGHT_HILL_NOISE_SCALE: f32 = 0.004;
/// Peak hill bump in world units (± this, low-frequency, applied everywhere so hills exist
/// without any ridge).
pub const HEIGHT_HILL_AMPLITUDE: f32 = WORLD_HEIGHT_PER_LEVEL * 0.75;

/// World-grid inputs the height field needs. Mirrors the relevant `MapConfig` fields.
#[derive(Clone, Copy)]
pub struct HeightfieldConfig {
    pub chunk_hex_radius: i32,
    pub chunk_cols: i32,
    pub chunk_rows: i32,
    pub hex_outer_radius: f32,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum TerrainClass {
    Plain,
    Hill,
    Mountain,
}

fn terrain_class(unit_noise: f32) -> TerrainClass {
    if unit_noise < TERRAIN_CLASS_HILL_MAX {
        TerrainClass::Plain
    } else if unit_noise < TERRAIN_CLASS_MOUNTAIN_MAX {
        TerrainClass::Hill
    } else {
        TerrainClass::Mountain
    }
}

// ===== Geometry =====

/// XZ offset of corner `dir` from the hex center, pointy-top at angle `60×dir − 30°`. Lockstep
/// with MSTHexMath.hex_corner_offset (client/addons/MarchingSquaresTerrain/algorithm/terrain/
/// mst_hex_math.gd:105-108) and the chunk mesh's corner use
/// (marching_squares_terrain_chunk.gd:456) — `size` is the hex outer radius.
fn corner_offset(dir: usize, r_outer: f32) -> (f32, f32) {
    let angle = (60.0 * dir as f32 - 30.0).to_radians();
    (r_outer * angle.cos(), r_outer * angle.sin())
}

/// The three `(hex_q, hex_r, corner_dir)` representations of one geometric corner: corner
/// `dir` of `(q, r)` is also corner `(dir + 4) % 6` of the `dir` neighbor and corner
/// `(dir + 2) % 6` of the `(dir + 5) % 6` neighbor.
fn corner_owners(q: i32, r: i32, dir: usize) -> [(i32, i32, usize); 3] {
    let a = HEX_NEIGHBOR_DELTAS[dir];
    let b = HEX_NEIGHBOR_DELTAS[(dir + 5) % 6];
    [
        (q, r, dir),
        (q + a.0, r + a.1, (dir + 4) % 6),
        (q + b.0, r + b.1, (dir + 2) % 6),
    ]
}

/// World XZ of the corner `dir` of hex `(q, r)`, canonicalized to the lexicographically
/// smallest owning hex so all 3 owners compute bit-identical coordinates. A plain
/// `hex_to_world(q, r) + corner_offset(dir)` would differ in the last float bit between
/// owners; sampling a global height function at a bit-identical point is what makes the seams
/// crack-free.
pub fn canonical_corner_world(q: i32, r: i32, dir: usize, r_outer: f32) -> (f32, f32) {
    let mut best = (q, r, dir);
    for (cq, cr, cd) in corner_owners(q, r, dir) {
        if (cq, cr) < (best.0, best.1) {
            best = (cq, cr, cd);
        }
    }
    let (cx, cz) = hex_to_world(best.0, best.1, r_outer);
    let (ox, oz) = corner_offset(best.2, r_outer);
    (cx + ox, cz + oz)
}

#[derive(Clone, Copy)]
struct Segment {
    ax: f32,
    az: f32,
    bx: f32,
    bz: f32,
}

// Squared point-to-segment distance in XZ (exact, including the endpoint clamps).
fn point_segment_dist_sq(px: f32, pz: f32, seg: &Segment) -> f32 {
    let abx = seg.bx - seg.ax;
    let abz = seg.bz - seg.az;
    let apx = px - seg.ax;
    let apz = pz - seg.az;
    let len_sq = abx * abx + abz * abz;
    let t = if len_sq > 0.0 {
        ((apx * abx + apz * abz) / len_sq).clamp(0.0, 1.0)
    } else {
        0.0
    };
    let dx = apx - t * abx;
    let dz = apz - t * abz;
    dx * dx + dz * dz
}

// ===== Union-find =====

struct Dsu {
    parent: Vec<usize>,
    size: Vec<usize>,
}

impl Dsu {
    fn new(n: usize) -> Self {
        Dsu { parent: (0..n).collect(), size: vec![1; n] }
    }

    fn find(&mut self, mut i: usize) -> usize {
        while self.parent[i] != i {
            self.parent[i] = self.parent[self.parent[i]];
            i = self.parent[i];
        }
        i
    }

    fn union(&mut self, a: usize, b: usize) {
        let (mut ra, mut rb) = (self.find(a), self.find(b));
        if ra == rb {
            return;
        }
        if self.size[ra] < self.size[rb] {
            std::mem::swap(&mut ra, &mut rb);
        }
        self.parent[rb] = ra;
        self.size[ra] += self.size[rb];
    }
}

// ===== Sampling =====

fn lerp(a: f32, b: f32, t: f32) -> f32 {
    a + (b - a) * t
}

struct HeightSampler<'a> {
    seed: u64,
    ridge_reach: f32,
    border_reach: f32,
    border_segments: &'a [Segment],
    ridge_segments: &'a [Segment],
    max_height: f32,
}

impl HeightSampler<'_> {
    fn base_height(&self, x: f32, z: f32) -> f32 {
        let octave1 = value_noise2d(x, z, HEIGHT_BASE_OCTAVE1_SCALE, self.seed ^ HEIGHT_NOISE_SEED_OFFSET);
        let octave2 = value_noise2d(x, z, HEIGHT_BASE_OCTAVE2_SCALE, self.seed ^ HEIGHT_NOISE_OCTAVE2_SEED_OFFSET);
        (octave1 * HEIGHT_BASE_OCTAVE1_WEIGHT + octave2 * HEIGHT_BASE_OCTAVE2_WEIGHT) * HEIGHT_BASE_AMPLITUDE
    }

    /// Distance to the nearest class-border edge, capped at `border_reach`. Global: identical
    /// for the same point no matter which hex samples it.
    fn border_dist(&self, x: f32, z: f32) -> f32 {
        let mut best_sq = f32::MAX;
        for seg in self.border_segments {
            let d_sq = point_segment_dist_sq(x, z, seg);
            if d_sq < best_sq {
                best_sq = d_sq;
            }
        }
        if best_sq == f32::MAX {
            return self.border_reach;
        }
        best_sq.sqrt().min(self.border_reach)
    }

    /// Distance to the nearest ridge polyline segment, `None` when every ridge segment is
    /// beyond `ridge_reach`. Global, same as `border_dist`.
    fn ridge_dist(&self, x: f32, z: f32) -> Option<f32> {
        let mut best_sq = f32::MAX;
        for seg in self.ridge_segments {
            let d_sq = point_segment_dist_sq(x, z, seg);
            if d_sq < best_sq {
                best_sq = d_sq;
            }
        }
        if best_sq == f32::MAX {
            return None;
        }
        let dist = best_sq.sqrt();
        if dist > self.ridge_reach { None } else { Some(dist) }
    }

    fn sample(&self, x: f32, z: f32) -> f32 {
        let base = self.base_height(x, z);
        let border = self.border_dist(x, z);

        // Ridge blend. The spec's literal `+inf beyond reach` would drop `t` from
        // `border/(border + reach)` to 0 in one step — a multi-level scarp ring around every
        // mountain. Folding the reach falloff into an effective distance
        // (`d / (1 - d/reach)`) keeps the formula and makes the transition continuous: it
        // diverges to +inf exactly at the reach radius.
        let t = match self.ridge_dist(x, z) {
            None => 0.0,
            Some(dist) => {
                let fade = (1.0 - dist / self.ridge_reach).clamp(0.0, 1.0);
                if fade <= 0.0 {
                    0.0
                } else {
                    let effective = dist / fade;
                    let denom = border + effective;
                    if denom <= 0.0 { 0.0 } else { border / denom }
                }
            }
        };

        let mut y = lerp(base, RIDGE_TOP_HEIGHT, t);

        // Sota-style erosion: strongest near the ridge top, zero at the base.
        let erosion_t = (4.0 * y / RIDGE_TOP_HEIGHT).clamp(0.0, 1.0);
        let erosion_noise = value_noise2d(x, z, EROSION_NOISE_SCALE, self.seed ^ RIDGE_NOISE_SEED_OFFSET);
        y -= erosion_t * erosion_noise * EROSION_AMPLITUDE;

        // Global hill bump so hill/plain terrain is not just the base octaves. Zero-centered
        // so level 0 (the flat ocean) stays reachable.
        let hill_noise = value_noise2d(x, z, HEIGHT_HILL_NOISE_SCALE, self.seed ^ HEIGHT_HILL_NOISE_SEED_OFFSET);
        y += (hill_noise - 0.5) * 2.0 * HEIGHT_HILL_AMPLITUDE;

        y.clamp(0.0, self.max_height)
    }
}

// ===== Generation =====

/// A mountain group's ridge polyline: a canonical sorted walk from the group's smallest
/// `(q, r)` member toward its largest, choosing among unvisited same-group neighbors in
/// `HEX_NEIGHBOR_DELTAS` order via the PRNG. `draw` is the local ridge walk counter — this
/// function never touches the generation pipeline's shared draw counter.
fn ridge_walk(
    group: &[usize],
    root: usize,
    dsu: &mut Dsu,
    index_of: &HashMap<(i32, i32), usize>,
    cells: &[(i32, i32)],
    cfg: &HeightfieldConfig,
    seed: u64,
    draw: &mut u64,
) -> Vec<usize> {
    let mut visited: HashSet<usize> = HashSet::new();
    let start = group[0];
    let target = *group.last().unwrap();
    let mut path = vec![start];
    visited.insert(start);
    let mut cur = start;

    while cur != target {
        let (q, r) = cells[cur];
        let neighbors = wrapped_hex_neighbors(q, r, cfg.chunk_hex_radius, cfg.chunk_cols, cfg.chunk_rows);
        let mut candidates: Vec<usize> = Vec::new();
        for (nq, nr) in neighbors {
            if let Some(&next) = index_of.get(&(nq, nr)) {
                if dsu.find(next) == root && !visited.contains(&next) {
                    candidates.push(next);
                }
            }
        }
        if candidates.is_empty() {
            break;
        }
        let next = candidates[pick_index(candidates.len(), seed, draw)];
        visited.insert(next);
        path.push(next);
        cur = next;
    }

    path
}

/// Subdivide a polyline of hex centers into ridge segments, jittering interior vertices
/// laterally with the PRNG (Sota's `create_dfs_random` fracture spirit, made deterministic).
fn subdivide_polyline(
    path: &[usize],
    centers: &[(f32, f32)],
    r_outer: f32,
    seed: u64,
    draw: &mut u64,
    out: &mut Vec<Segment>,
) {
    for pair in path.windows(2) {
        let (ax, az) = centers[pair[0]];
        let (bx, bz) = centers[pair[1]];
        let dx = bx - ax;
        let dz = bz - az;
        let len = (dx * dx + dz * dz).sqrt();
        let (nx, nz) = if len > 0.0 { (-dz / len, dx / len) } else { (0.0, 0.0) };
        let mut prev = (ax, az);
        for step in 1..RIDGE_SUBDIVISIONS {
            let f = step as f32 / RIDGE_SUBDIVISIONS as f32;
            let jitter = (next_unit(seed, draw) - 0.5) * 2.0 * RIDGE_LATERAL_JITTER_FRACTION * r_outer;
            let px = ax + dx * f + nx * jitter;
            let pz = az + dz * f + nz * jitter;
            out.push(Segment { ax: prev.0, az: prev.1, bx: px, bz: pz });
            prev = (px, pz);
        }
        out.push(Segment { ax: prev.0, az: prev.1, bx, bz });
    }
}

/// Everything the global height function needs besides the sampler constants: hex centers and
/// the two global segment lists. Built once per generation.
struct FieldGeometry {
    centers: Vec<(f32, f32)>,
    border_segments: Vec<Segment>,
    ridge_segments: Vec<Segment>,
}

fn build_geometry(cells: &[(i32, i32)], cfg: &HeightfieldConfig, seed: u64) -> FieldGeometry {
    let r_outer = cfg.hex_outer_radius;
    let mut index_of: HashMap<(i32, i32), usize> = HashMap::with_capacity(cells.len());
    for (i, &cell) in cells.iter().enumerate() {
        index_of.insert(cell, i);
    }

    // 1. Per-hex terrain class (class field sampled at the hex center).
    let class_seed = seed ^ TERRAIN_CLASS_NOISE_SEED_OFFSET;
    let mut centers: Vec<(f32, f32)> = Vec::with_capacity(cells.len());
    let mut classes: Vec<TerrainClass> = Vec::with_capacity(cells.len());
    for &(q, r) in cells {
        let (wx, wz) = hex_to_world(q, r, r_outer);
        centers.push((wx, wz));
        classes.push(terrain_class(value_noise2d(wx, wz, TERRAIN_CLASS_NOISE_SCALE, class_seed)));
    }

    // 2. DSU over same-class wrapped neighbors.
    let mut dsu = Dsu::new(cells.len());
    for (i, &(q, r)) in cells.iter().enumerate() {
        let neighbors = wrapped_hex_neighbors(q, r, cfg.chunk_hex_radius, cfg.chunk_cols, cfg.chunk_rows);
        for (nq, nr) in neighbors {
            if let Some(&j) = index_of.get(&(nq, nr)) {
                if classes[j] == classes[i] {
                    dsu.union(i, j);
                }
            }
        }
    }

    // 3. Canonical groups: sort by lexicographically smallest member, then members by (q, r).
    let mut members_by_root: HashMap<usize, Vec<usize>> = HashMap::new();
    for i in 0..cells.len() {
        let root = dsu.find(i);
        members_by_root.entry(root).or_default().push(i);
    }
    let mut groups: Vec<Vec<usize>> = members_by_root.into_values().collect();
    for group in &mut groups {
        group.sort_by_key(|&i| cells[i]);
    }
    groups.sort_by_key(|group| cells[group[0]]);

    // 4. Ridge polylines for MOUNTAIN groups only, in canonical group order. The walk draws
    //    from a local counter seeded from `seed` — the shared generation `draw` is untouched.
    let mut ridge_segments: Vec<Segment> = Vec::new();
    let mut ridge_draw: u64 = 0;
    for group in &groups {
        if group.len() < 2 || classes[group[0]] != TerrainClass::Mountain {
            continue;
        }
        let root = dsu.find(group[0]);
        let path = ridge_walk(group, root, &mut dsu, &index_of, cells, cfg, seed, &mut ridge_draw);
        subdivide_polyline(&path, &centers, r_outer, seed, &mut ridge_draw, &mut ridge_segments);
    }

    // 5. Class-border edges: one segment per edge whose two hexes differ in class, inserted
    //    once (from the lexicographically smaller hex) in cell/direction order.
    let mut border_segments: Vec<Segment> = Vec::new();
    for (i, &(q, r)) in cells.iter().enumerate() {
        let neighbors = wrapped_hex_neighbors(q, r, cfg.chunk_hex_radius, cfg.chunk_cols, cfg.chunk_rows);
        for (dir, (nq, nr)) in neighbors.into_iter().enumerate() {
            if (nq, nr) <= (q, r) {
                continue;
            }
            let Some(&j) = index_of.get(&(nq, nr)) else { continue };
            if classes[j] == classes[i] {
                continue;
            }
            let (ax, az) = canonical_corner_world(q, r, dir, r_outer);
            let (bx, bz) = canonical_corner_world(q, r, (dir + 1) % 6, r_outer);
            border_segments.push(Segment { ax, az, bx, bz });
        }
    }

    FieldGeometry { centers, border_segments, ridge_segments }
}

fn make_sampler<'a>(cfg: &HeightfieldConfig, seed: u64, geometry: &'a FieldGeometry) -> HeightSampler<'a> {
    HeightSampler {
        seed,
        ridge_reach: cfg.hex_outer_radius * RIDGE_REACH_HEXES,
        border_reach: cfg.hex_outer_radius * BORDER_REACH_HEXES,
        border_segments: &geometry.border_segments,
        ridge_segments: &geometry.ridge_segments,
        max_height: ELEVATION_LEVELS as f32 * WORLD_HEIGHT_PER_LEVEL,
    }
}

/// Generate the whole world's height payloads: one `HEIGHTS_PER_HEX`-entry `Vec<i16>` per hex
/// (`[center, c0..c5]`, world-unit Y). Pure function of `(cells, cfg, seed)` — the returned
/// map's iteration order is not part of the contract, the per-hex vectors are.
pub fn generate_heightfield(
    cells: &[(i32, i32)],
    cfg: &HeightfieldConfig,
    seed: u64,
) -> HashMap<(i32, i32), Vec<i16>> {
    let r_outer = cfg.hex_outer_radius;
    let geometry = build_geometry(cells, cfg, seed);
    let sampler = make_sampler(cfg, seed, &geometry);

    let mut field: HashMap<(i32, i32), Vec<i16>> = HashMap::with_capacity(cells.len());
    for (i, &(q, r)) in cells.iter().enumerate() {
        let (cx, cz) = geometry.centers[i];
        let mut heights = Vec::with_capacity(HEIGHTS_PER_HEX);
        heights.push(quantize(sampler.sample(cx, cz), sampler.max_height));
        for dir in 0..6 {
            let (px, pz) = canonical_corner_world(q, r, dir, r_outer);
            heights.push(quantize(sampler.sample(px, pz), sampler.max_height));
        }
        field.insert((q, r), heights);
    }
    field
}

/// Samples the exact same field (unquantized, world units) at arbitrary world XZ points — the
/// verification/continuity hook: the payloads are this function evaluated at hex centers and
/// canonical corners. Pure function of `(cells, cfg, seed, points)`. Not read by gameplay code
/// yet; the seam/continuity tests (standalone crate under the task's temp dir) call it.
#[allow(dead_code)]
pub fn sample_heightfield_at(
    cells: &[(i32, i32)],
    cfg: &HeightfieldConfig,
    seed: u64,
    points: &[(f32, f32)],
) -> Vec<f32> {
    let geometry = build_geometry(cells, cfg, seed);
    let sampler = make_sampler(cfg, seed, &geometry);
    points.iter().map(|&(x, z)| sampler.sample(x, z)).collect()
}

/// World-unit height → the stored i16 payload. Rounding (not truncation) keeps the payload
/// symmetric around the sample; the level derivation below reads the same quantized value, so
/// a hex's level is always consistent with its stored center height.
fn quantize(y: f32, max_height: f32) -> i16 {
    y.round().clamp(0.0, max_height) as i16
}

/// `BuildingTile.elevation` for a stored center height: `floor(height / WORLD_HEIGHT_PER_LEVEL)`
/// clamped to `0..ELEVATION_LEVELS-1`. Monotonic and clamped by construction.
pub fn elevation_level(center_height: i16) -> i16 {
    ((center_height as f32 / WORLD_HEIGHT_PER_LEVEL).floor() as i16).clamp(0, ELEVATION_LEVELS - 1)
}
